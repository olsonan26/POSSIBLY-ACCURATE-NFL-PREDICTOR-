import { existsSync,readFileSync,writeFileSync } from 'node:fs';
import {horizonDelta} from '../services/researchSnapshot.js';
const read=(path:string)=>existsSync(path)?JSON.parse(readFileSync(path,'utf8')):null;
const historical=read('research/runtime/discovery-summary.json');
const durable=read('research/runtime/durable/discovery-summary.json');
const coach=read('research/runtime/coach-section-scorecard.durable.json');
const snapshots=read('research/runtime/prediction-snapshots.json')||[];
const frozen=read('research/runtime/durable/prediction-snapshots.json')||[];
const fields=[...new Set<string>(snapshots.flatMap((s:any)=>Object.keys(s.unifiedSnapshot?.features||{})))];
const known=[...new Set<string>(snapshots.flatMap((s:any)=>Object.entries(s.unifiedSnapshot?.features||{}).filter(([,f]:any)=>f.status==='known').map(([k])=>k)))];
const horizonDeltas:any[]=[];
for(const key of [...new Set(frozen.map((s:any)=>`${s.gameId}:${s.sourceModelVersion}`))]) {
  const group=frozen.filter((s:any)=>`${s.gameId}:${s.sourceModelVersion}`===key).sort((a:any,b:any)=>Date.parse(a.predictionTimestamp)-Date.parse(b.predictionTimestamp));
  for(let i=1;i<group.length;i++) {
    const a=group[i-1].unifiedSnapshot,b=group[i].unifiedSnapshot;
    if(Date.parse(a.capturedAt)>=Date.parse(b.capturedAt))continue;
    const delta=horizonDelta(a,b);
    horizonDeltas.push({gameId:b.gameId,from:a.captureHorizon,to:b.captureHorizon,probabilityDelta:delta['football_core.homeProbability'],
      marketDelta:delta['football_market.homeProbability'],weatherWindDelta:delta['football_weather.windSpeedMph'],
      coachProtectionDelta:delta['coach_protection.direction'],dataQualityDelta:delta['data_quality.coverage']});
  }
}
const summary={generatedAt:new Date().toISOString(),controlModel:'v2.2-validated-current-season',historical,durable,
  snapshot:{families:new Set(fields.map(k=>k.split('.')[0])).size,fields:fields.length,fieldsEverKnown:known.length,
    missingOrBlocked:fields.filter(k=>!known.includes(k)),knownFields:known,example:snapshots.find((s:any)=>s.week===7)?.unifiedSnapshot||null},
  coach:coach?{prospectiveReports:coach.prospectiveReports,historicalReports:coach.historicalReconstructions,sections:coach.prospective}:null,
  horizons:[...new Set(frozen.map((s:any)=>s.unifiedSnapshot?.captureHorizon))].map(horizon=>({horizon,forecasts:frozen.filter((s:any)=>s.unifiedSnapshot?.captureHorizon===horizon).length})),
  completedUniqueGames:new Set(frozen.filter((s:any)=>s.actualWinner).map((s:any)=>s.gameId)).size,
  horizonDeltas,
  activeExperiment:read('research/runtime/active-experiment-manifest.json'),
  researchQueue:read('research/runtime/combined-research-queue.json')||[],
  shadowLeaderboard:read('research/runtime/durable/shadow-leaderboard.json')||[],
  weatherAcceptance:read('research/runtime/weather-acceptance.json'),
  verification:read('research/runtime/verification.json')};
writeFileSync('research/reports/v2-summary.json',JSON.stringify(summary,null,2));
writeFileSync('research/reports/v2-summary.ts',`// Generated by bun run research:summary. Values describe the recorded run, not live state.\nexport default ${JSON.stringify(summary,null,2)};\n`);
console.log(JSON.stringify({historical,durable,fields:fields.length,knownFields:known.length,families:summary.snapshot.families}));
